#!/usr/bin/env python3
"""Generate the web installer art from Koprulu's classic repack and the retail StarCraft executable.

Requires Pillow, pefile and StormLib. The executable is read as a PE resource file.
"""

import argparse
import ctypes.util
import io
import json
import struct
from pathlib import Path

import pefile
from PIL import Image

from import_discs import Storm


def original_icon(executable):
    pe = pefile.PE(str(executable))
    try:
        icons = next(group for group in pe.DIRECTORY_ENTRY_RESOURCE.entries if group.id == 3)
        candidates = []
        for resource in icons.directory.entries:
            info = resource.directory.entries[0].data.struct
            dib = pe.get_data(info.OffsetToData, info.Size)
            width, double_height = struct.unpack_from('<II', dib, 4)
            depth = struct.unpack_from('<H', dib, 14)[0]
            if width <= 256 and double_height == width * 2:
                candidates.append((width, depth, dib))
        width, depth, dib = max(candidates, key=lambda item: item[:2])
        entry = struct.pack('<4BHHII', width % 256, width % 256, 0, 0, 1, depth, len(dib), 22)
        ico = struct.pack('<3H', 0, 1, 1) + entry + dib
        return Image.open(io.BytesIO(ico)).convert('RGBA')
    finally:
        pe.close()


def bitmap_sheet(data, colors, empty, full, output):
    if data[:4] != b'FONT':
        raise ValueError('Invalid StarCraft FNT header')
    low, high, w, h = data[4:8]
    cell_w, cell_h = w + 2, h + 2
    bar_y = cell_h * 6
    atlas = Image.new('RGBA', (max(16 * cell_w, empty.width), bar_y + 2 * empty.height))
    widths = []
    for code in range(32, 127):
        off = struct.unpack_from('<I', data, 8 + 4 * (code - low))[0] if low <= code <= high else 0
        if not off:
            widths.append(w // 2 if code == 32 else 0)
            continue
        gw, gh, dx, dy = data[off:off + 4]
        widths.append(w // 2 if code == 32 else dx + gw + 1)
        x = (code - 32) % 16 * cell_w + dx
        y = (code - 32) // 16 * cell_h + dy
        cursor, pos = off + 4, 0
        while pos < gw * gh:
            packet = data[cursor]
            cursor += 1
            skip, color = packet >> 3, packet & 7
            pos += skip
            if pos >= gw * gh:
                break
            if not skip or color:
                atlas.putpixel((x + pos % gw, y + pos // gw), (*colors[color], 255))
                pos += 1
    atlas.paste(empty, (0, bar_y))
    atlas.paste(full, (0, bar_y + empty.height))
    atlas.save(output / 'sprites.png', optimize=True)
    metrics = dict(width=cell_w, height=cell_h, advances=widths, barY=bar_y, barW=empty.width, barH=empty.height)
    (output / 'font-metrics.js').write_text('// Generated by tools/build_launcher_art.py\nexport default ' +
                                            json.dumps(metrics, separators=(',', ':')) + ';\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('core', type=Path)
    parser.add_argument('exe', type=Path, help='StarCraft.exe from the Brood War CD')
    parser.add_argument('--stormlib', default=ctypes.util.find_library('storm'))
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'site/ui')
    args = parser.parse_args()
    if not args.stormlib:
        parser.error('Supply --stormlib PATH to the StormLib shared library')
    args.output.mkdir(parents=True, exist_ok=True)
    storm = Storm(args.stormlib)
    with storm.archive(args.core) as archive:
        def pcx(name):
            return Image.open(io.BytesIO(storm.read(archive, name)))
        pcx(r'glue\title\title.pcx').save(args.output / 'loading.png', optimize=True)
        palette = pcx(r'glue\title\tfont.pcx').convert('RGB')
        colors = [palette.getpixel((16 + i, 0)) for i in range(8)]
        # The console blits these indexed sprites through the current terrain palette.
        wpe = storm.read(archive, r'tileset\badlands.wpe')
        terrain_palette = bytes(c for i in range(0, 1024, 4) for c in wpe[i:i + 3])
        empty, full = pcx(r'game\tpbrempt.pcx'), pcx(r'game\tpbrfull.pcx')
        for bar in (empty, full):
            bar.putpalette(terrain_palette)
        bitmap_sheet(storm.read(archive, r'files\font\font16.fnt'), colors, empty, full, args.output)
    icon = original_icon(args.exe)
    for size in (180, 192, 512):
        scale = max(1, int(size * 0.9 / icon.width))
        art = icon.resize((icon.width * scale, icon.height * scale), Image.Resampling.NEAREST)
        target = Image.new('RGB', (size, size), 'black')
        target.paste(art, ((size - art.width) // 2, (size - art.height) // 2), art)
        target.save(args.output / f'icon-{size}.png', optimize=True)


if __name__ == '__main__':
    main()
